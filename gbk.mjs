export function countGbkBytes(text) {
  let byteLength = 0;

  for (const character of text) {
    const codePoint = character.codePointAt(0);
    if (codePoint <= 0x7f) {
      byteLength += 1;
      continue;
    }

    let low = 0;
    let high = GBK_TWO_BYTE_RANGES.length - 1;
    let isSupported = false;
    while (low <= high) {
      const middle = Math.floor((low + high) / 2);
      const [start, end] = GBK_TWO_BYTE_RANGES[middle];
      if (codePoint < start) {
        high = middle - 1;
      } else if (codePoint > end) {
        low = middle + 1;
      } else {
        isSupported = true;
        break;
      }
    }
    if (!isSupported) return null;
    byteLength += 2;
  }

  return byteLength;
}
